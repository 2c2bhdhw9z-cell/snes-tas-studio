#!/usr/bin/env python3
"""Writes Packages/SignKit/Sources/SignKit/Certs/AppleCertificates.swift.

The files come straight from Apple's public certificate page:
  https://www.apple.com/certificateauthority/
Usage:  python3 tools/gen-apple-certs.py <folder with the .cer files>

Real signed apps (Apple's own tool, and every working signer) carry these
certificates inside the signature. iOS needs them to link your certificate back
to Apple, and a .p12 file usually only contains your own certificate.
"""
import base64, sys, pathlib, textwrap

FILES = [
    ("AppleIncRootCertificate.cer", "Apple Root CA"),
    ("AppleRootCA-G2.cer",          "Apple Root CA - G2"),
    ("AppleRootCA-G3.cer",          "Apple Root CA - G3"),
    ("AppleWWDRCAG2.cer",           "Apple Worldwide Developer Relations CA - G2"),
    ("AppleWWDRCAG3.cer",           "Apple Worldwide Developer Relations CA - G3"),
    ("AppleWWDRCAG4.cer",           "Apple Worldwide Developer Relations CA - G4"),
    ("AppleWWDRCAG5.cer",           "Apple Worldwide Developer Relations CA - G5"),
    ("AppleWWDRCAG6.cer",           "Apple Worldwide Developer Relations CA - G6"),
]

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parent.parent / "Packages/SignKit/Sources/SignKit/Certs/AppleCertificates.swift"

lines = ["// Generated by tools/gen-apple-certs.py — do not edit by hand.",
         "// Apple's public root and developer-relations certificates (https://www.apple.com/certificateauthority/).",
         "",
         "enum AppleCertificateData {",
         "    /// (name, base64 DER, split over several lines)",
         "    static let all: [(String, String)] = ["]
for fname, label in FILES:
    der = (src / fname).read_bytes()
    b64 = base64.b64encode(der).decode()
    wrapped = textwrap.wrap(b64, 76)
    # One multi-line string per certificate. (A long chain of "a" + "b" + ... can make
    # the Swift compiler give up with "expression too complex"; this cannot.)
    lines.append(f'        ("{label}", """')
    for w in wrapped:
        lines.append(f'            {w}')
    lines.append('            """),')
lines.append("    ]")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print("wrote", out, out.stat().st_size, "bytes")
